        /// <summary>Kretsens inkorg och beslutade ansökningar för ett tävlingsår.</summary>
        [HttpGet]
        public async Task<IActionResult> GetRegionApplications(int regionId, int? year)
        {
            var auth = await KretsAuthorityAsync(regionId);
            if (!auth.Allowed) return Json(new { success = false, message = "Åtkomst nekad" });
            var y = year ?? DateTime.Today.Year + 1;
            var list = SafeList(() => _apps.ForRegion(regionId, new DateTime(y, 1, 1), new DateTime(y, 12, 31)));
            // ⚠️ En ansökan som väntar på kretsen visas ALLTID — årsväljaren får aldrig gömma arbete.
            // (Samma fel som granskningsinkorgen hade: en inskickad ansökan för ett annat år syntes inte.)
            var shown = list.Select(a => a.Id).ToHashSet();
            list.AddRange(SafeList(() => _apps.ForRegion(regionId, new DateTime(2000, 1, 1), new DateTime(2100, 12, 31)))
                .Where(a => a.Status == CompetitionApplicationStatus.Inskickad && !shown.Contains(a.Id)));
            var region = _calendar.Region(regionId);
            return Json(new
            {
                success = true,
                year = y,
                region = region == null ? null : new { id = region.Id, name = region.Name },
                forbundetDeadline = CompetitionApplicationRules.ForbundetDeadline(y).ToString("yyyy-MM-dd"),
                deadlines = SafeList(() => _apps.Deadlines(regionId)).Where(d => d.Year == y)
                    .Select(d => new { d.Level, lastDate = d.LastDate.ToString("yyyy-MM-dd") }),
                applications = list.Where(a => a.Status != CompetitionApplicationStatus.Utkast).Select(a => Dto(a, forClub: false)),
                actingAs = auth.Role
            });
        }

        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> RequestCompletion(int id, string? text)
        {
            var (a, who, deny) = await KretsActionAsync(id);
            if (deny != null) return deny;
            var (saved, err) = _apps.RequestCompletion(id, text ?? "", who!);
            if (saved == null) return Json(new { success = false, message = err });
            var n = await NotifyClubAsync(saved, who!, $"Kretsen ber om komplettering av ansökan \"{saved.Name}\"",
                new[] { $"{who!.Name} i {RegionName(saved.RegionId)} ber er komplettera ansökan om {saved.Name} ({saved.CompetitionDate:yyyy-MM-dd}):", saved.CompletionRequest ?? "",
                        "Svara i klubbens Administration → Tävlingar → Ansökningar. Ansökan ligger kvar hos kretsen under tiden." });
            return Json(new { success = true, notified = n, message = MailMessage(n, "Klubben är ombedd att komplettera") });
        }

        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> DecideApplication(int id, string? decision, string? text)
        {
            var (a, who, deny) = await KretsActionAsync(id);
            if (deny != null) return deny;
            var approve = decision == "approve";
            if (!approve && decision != "reject") return Json(new { success = false, message = "Okänt beslut." });
            var (saved, err) = _apps.Decide(id, approve, text, who!);
            if (saved == null) return Json(new { success = false, message = err });
            _calendar.Invalidate();
            var n = await NotifyClubAsync(saved, who!,
                approve ? $"Godkänd: {saved.Name}" : $"Avslagen: {saved.Name}",
                approve
                    ? new[] { $"{RegionName(saved.RegionId)} har godkänt ansökan om {saved.Name} den {saved.CompetitionDate:yyyy-MM-dd}.", saved.DecisionText ?? "",
                              "När ni vill lägga in tävlingen: gå till klubbens Administration → Tävlingar → Ansökningar och tryck Skapa tävlingen. Guiden är då förifylld med det ansökan innehåller." }
                    : new[] { $"{RegionName(saved.RegionId)} har avslagit ansökan om {saved.Name}.", "Motivering:", saved.DecisionText ?? "" });
            return Json(new { success = true, notified = n, message = MailMessage(n, approve ? "Ansökan är godkänd" : "Ansökan är avslagen") });
        }

