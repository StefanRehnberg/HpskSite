        /// <summary>Om ansökan kom (eller skulle komma) efter kretsens sista dag eller Förbundets gräns.</summary>
        private string? LateNote(CompetitionApplication a)
        {
            var when = a.SubmittedAt ?? DateTime.Today;
            if (a.NeedsForbundet && CompetitionApplicationRules.IsLate(when, CompetitionApplicationRules.ForbundetDeadline(a.CompetitionDate.Year)))
                return $"Förbundets sista dag för {a.CompetitionDate.Year} var {CompetitionApplicationRules.ForbundetDeadline(a.CompetitionDate.Year).ToString("d MMMM yyyy", new CultureInfo("sv-SE"))}. Kretsen kan skicka den som komplettering.";
            DateTime? last = null;
            try { last = _apps.DeadlineFor(a.RegionId, a.CompetitionDate.Year, a.Level); } catch { }
            if (last.HasValue && CompetitionApplicationRules.IsLate(when, last.Value))
                return $"Kretsens sista ansökningsdag var {last.Value.ToString("d MMMM yyyy", new CultureInfo("sv-SE"))}.";
            return null;
        }

        /// <summary>
        /// Aviserar kretsen. Med en tävlingsansvarig: personerna, med en knapp till inkorgen. Utan:
        /// länkläget — kretsens kontaktadress får en länk som fungerar utan inloggning, och
        /// kretsadministratörerna (inloggade) får inkorgen.
        /// </summary>
        private async Task<int> NotifyKretsAsync(CompetitionApplication a, Umbraco.Cms.Core.Models.IMember actor, string headline)
        {
            try
            {
                var rec = _uppdrag.Recipients(a.RegionId, BoardRoleDefinitions.RoleTavlingsansvarig);
                var base_ = $"{Request.Scheme}://{Request.Host}";
                var inbox = $"{base_}/kretsen/ansokningar?krets={a.RegionId}";
                var club = a.ClubId > 0 ? (_clubs.GetClubNameById(a.ClubId) ?? "") : RegionName(a.RegionId);
                var level = CompetitionLevel.Find(a.Level)?.Label?.ToLowerInvariant() ?? a.Level;
                var paras = new List<string>
                {
                    $"{club} ansöker om att arrangera {a.Name} ({level}, {ActivityDiscipline.Label(a.Discipline).ToLowerInvariant()}) den {a.CompetitionDate:yyyy-MM-dd}.",
                    string.IsNullOrWhiteSpace(a.Place) ? "" : $"Plats: {a.Place}",
                    string.IsNullOrWhiteSpace(a.Note) ? "" : $"Meddelande: {a.Note}",
                    a.Status == CompetitionApplicationStatus.Inskickad && !string.IsNullOrEmpty(a.CompletionReply) ? $"Klubbens komplettering: {a.CompletionReply}" : "",
                    a.NeedsForbundet ? "En nationell tävling och en landsdelstävling beslutas av Förbundet. Kretsen tillstyrker eller avstyrker, och ansökan kommer med i kretsens sammanställning." : "Kretsen beslutar själv om en kretstävling."
                };
                var replyTo = _replyTo.ForPersonInClub(actor.Id, a.ClubId);
                int sent = 0;
                foreach (var r in rec.To)
                {
                    string url, btn, notice;
                    if (r.MemberId > 0)
                    {
                        url = inbox; btn = "Öppna kretsens ansökningar";
                        notice = rec.IsFallback
                            ? "Du får mejlet för att du är kretsadministratör och kretsen inte har utsett någon tävlingsansvarig."
                            : "Du får mejlet för att du är kretsens tävlingsansvarige.";
                    }
                    else
                    {
                        var token = _tokens.CreateCaseLink(CaseKind, a.Id, a.RegionId, Checksum(a), r.Email);
                        url = $"{base_}/kretsen/arende?t={Uri.EscapeDataString(token)}"; _caseLinks.Add(url); btn = "Granska ansökan";
                        notice = $"Kretsen har inte utsett någon tävlingsansvarig på pistol.nu, så ansökan kommer som en länk som fungerar utan inloggning i 60 dagar. "
                               + $"Utser kretsen någon hamnar nästa ansökan direkt hos den personen: {base_}/kretsen/kom-igang?krets={a.RegionId}";
                        try { _apps.SetLinkSentTo(a.Id, r.Email); } catch { }
                    }
                    if (await _email.SendKretsgranskningAsync(r.Email, r.Name, $"{headline}: {a.Name}", paras, btn, url, notice, replyTo))
                        sent++;
                }
                return sent;
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Ansökan {Id}: kretsen kunde inte aviseras.", a.Id);
                return 0;
            }
        }

        /// <summary>Besked till klubben: ansökans kontakt, klubbens kontaktadress och den som skapade den.</summary>
        private async Task<int> NotifyClubAsync(CompetitionApplication a, KretsDecider who, string subject, IEnumerable<string> paras)
        {
            try
            {
                var to = new List<(string Email, string Name)>();
                var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                void Add(string? e, string n) { if (!string.IsNullOrWhiteSpace(e) && seen.Add(e.Trim())) to.Add((e.Trim(), n)); }
                Add(a.ContactEmail, a.ContactName ?? "");
                var creator = _memberService.GetById(a.CreatedByMemberId);
                if (creator != null) Add(creator.Email, DisplayName(creator));
                if (a.ClubId > 0) Add(_clubs.GetClubById(a.ClubId)?.ContactEmail, _clubs.GetClubNameById(a.ClubId) ?? "");

                var replyTo = who.MemberId > 0 ? _replyTo.ForMember(who.MemberId) : _replyTo.ForRegion(a.RegionId);
                int sent = 0;
                foreach (var (email, name) in to)
                    if (await _email.SendKretsgranskningAsync(email, name, subject, paras, null, null,
                            $"Beslutet fattades av {who.Name} ({who.Role}).", replyTo))
                        sent++;
                return sent;
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Ansökan {Id}: klubben kunde inte aviseras.", a.Id);
                return 0;
            }
        }

        public static string Checksum(CompetitionApplication a) => CompetitionApplicationRules.Checksum(a);

        private (CompetitionApplication? App, CaseLinkPayload? Link, string? Error) ReadCaseLink(string? t)
        {
            var p = _tokens.ReadCaseLink(t);
            if (p == null || p.CaseKind != CaseKind) return (null, null, "Länken gäller inte längre. Den kan ha gått ut (den gäller i 60 dagar).");
            var a = _apps.Get(p.CaseId);
            if (a == null || a.RegionId != p.RegionId) return (null, null, "Ansökan finns inte längre.");
            if (Checksum(a) != p.Checksum)
                return (null, null, "Ansökan har ändrats sedan länken skickades, så länken gäller inte längre. En ny länk skickas när klubben skickar in ändringen.");
            return (a, p, null);
        }

        private async Task<(CompetitionApplication? App, Umbraco.Cms.Core.Models.IMember? Me, IActionResult? Deny)> ClubActionAsync(int id)
        {
            var a = _apps.Get(id);
            if (a == null) return (null, null, Json(new { success = false, message = "Ansökan hittades inte." }));
            var me = await CurrentMemberAsync();
            if (me == null) return (null, null, Json(new { success = false, message = "Logga in först." }));
            if (!await CanClubAsync(a.ClubId, a.RegionId)) return (null, null, Json(new { success = false, message = "Åtkomst nekad" }));
            return (a, me, null);
        }

        private async Task<(CompetitionApplication? App, KretsDecider? Who, IActionResult? Deny)> KretsActionAsync(int id, bool allowHosForbundet = false)
        {
            var a = _apps.Get(id);
            if (a == null) return (null, null, Json(new { success = false, message = "Ansökan hittades inte." }));
            var auth = await KretsAuthorityAsync(a.RegionId);
            if (!auth.Allowed) return (null, null, Json(new { success = false, message = "Åtkomst nekad" }));
            var me = await CurrentMemberAsync();
            return (a, new KretsDecider(me?.Id ?? 0, me == null ? "" : DisplayName(me), auth.Role, KretsChannel.Inloggad), null);
        }

        /// <summary>Klubbens sida: klubbens admin — eller kretsadmin för kretsens egna ansökningar.</summary>
        private async Task<bool> CanClubAsync(int clubId, int regionId)
        {
            if (clubId > 0) return await _auth.IsClubAdminForClub(clubId);
            var region = _calendar.Region(regionId);
            return region != null && await _auth.IsRegionalAdminForRegion(region.Code);
        }

        /// <summary>
        /// Kretsens sida: tävlingsansvarig, kretsadmin eller sajtadmin — och vilken roll som stämplas.
        /// </summary>
        private async Task<(bool Allowed, string Role)> KretsAuthorityAsync(int regionId)
        {
            var region = _calendar.Region(regionId);
            if (region == null) return (false, "");
            var me = await CurrentMemberAsync();
            if (me == null) return (false, "");
            if (_uppdrag.HasUppdrag(regionId, me.Id, BoardRoleDefinitions.RoleTavlingsansvarig))
                return (true, BoardRoleDefinitions.GetLabel(BoardRoleDefinitions.RoleTavlingsansvarig));
            if (await _auth.IsCurrentUserAdminAsync()) return (true, "Sajtadministratör (support)");
            if (await _auth.IsRegionalAdminForRegion(region.Code)) return (true, "Kretsadministratör");
            return (false, "");
        }

        /// <summary>
        /// Får besökaren se planeringskalendern? Kretsens tävlingsansvarige, kretsadmin, sajtadmin —
        /// eller administratör för en klubb i kretsen (de ansöker därifrån).
        /// </summary>
        private async Task<bool> CanPlanAsync(int regionId)
        {
            if ((await KretsAuthorityAsync(regionId)).Allowed) return true;
            var me = await CurrentMemberAsync();
            if (me == null) return false;
            foreach (var cid in _calendar.ClubsInRegion(regionId).Keys)
                if (await _auth.IsClubAdminForClub(cid)) return true;
            return false;
        }

