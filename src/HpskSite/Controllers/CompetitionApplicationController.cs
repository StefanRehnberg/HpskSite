        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> RegisterForbundetDecision(int id, string? decision, string? decisionDate, string? grantedDate, string? text)
        {
            var (a, who, deny) = await KretsActionAsync(id, allowHosForbundet: true);
            if (deny != null) return deny;
            var granted = decision == "granted";
            if (!granted && decision != "rejected") return Json(new { success = false, message = "Okänt beslut." });
            var dd = ParseDate(decisionDate) ?? DateTime.Today;
            var (saved, err) = _apps.RegisterForbundetDecision(id, granted, dd, ParseDate(grantedDate), text, who!);
            if (saved == null) return Json(new { success = false, message = err });
            _calendar.Invalidate();
            var moved = saved.GrantedDate.HasValue ? $" Förbundet har beviljat den {saved.GrantedDate:yyyy-MM-dd} i stället för {saved.CompetitionDate:yyyy-MM-dd}." : "";
            var hasComp = saved.CompetitionId is > 0;
            var n = await NotifyClubAsync(saved, who!,
                granted ? $"Förbundet har beviljat: {saved.Name}" : $"Förbundet har avslagit: {saved.Name}",
                new[] { granted ? $"Förbundet har beviljat ansökan om {saved.Name}.{moved}" : $"Förbundet har avslagit ansökan om {saved.Name}.",
                        saved.DecisionText ?? "",
                        granted && hasComp && saved.GrantedDate.HasValue ? "Tävlingen ni redan skapat har kvar det gamla datumet. Ändra det i tävlingens redigering." : "",
                        !granted && hasComp ? "Tävlingen ni redan skapat finns kvar. Ta bort den, eller gör om den till en kretstävling efter samråd med kretsen." : "" });
            return Json(new { success = true, notified = n, message = MailMessage(n, "Förbundets beslut är registrerat") });
        }

        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> MarkSentToForbundet(int regionId, string? ids)
        {
            var auth = await KretsAuthorityAsync(regionId);
            if (!auth.Allowed) return Json(new { success = false, message = "Åtkomst nekad" });
            var me = await CurrentMemberAsync();
            var idList = (ids ?? "").Split(',', StringSplitOptions.RemoveEmptyEntries)
                .Select(s => int.TryParse(s, out var i) ? i : 0).Where(i => i > 0)
                .Where(i => _apps.Get(i)?.RegionId == regionId).ToList();
            var n = _apps.MarkSentToForbundet(idList, me?.Id ?? 0, me == null ? "" : DisplayName(me));
            return Json(new { success = true, marked = n, message = $"{n} {(n == 1 ? "ansökan" : "ansökningar")} markerade som skickade till Förbundet." });
        }

        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> SetDeadline(int regionId, int year, string? level, string? lastDate)
        {
            var auth = await KretsAuthorityAsync(regionId);
            if (!auth.Allowed) return Json(new { success = false, message = "Åtkomst nekad" });
            var d = string.IsNullOrWhiteSpace(lastDate) ? null : ParseDate(lastDate);
            if (!string.IsNullOrWhiteSpace(lastDate) && d == null) return Json(new { success = false, message = "Ogiltigt datum." });
            var err = _apps.SetDeadline(regionId, year, level ?? "", d);
            return Json(err == null ? new { success = true, message = d == null ? "Sista dagen borttagen." : "Sista dagen sparad." } : new { success = false, message = err });
        }

