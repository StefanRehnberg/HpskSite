        /// <summary>Klubbens ansökningar, kretsens sista dagar och om kretsen tar emot inloggat.</summary>
        [HttpGet]
        public async Task<IActionResult> GetClubApplications(int clubId)
        {
            if (!await _auth.IsClubAdminForClub(clubId)) return Json(new { success = false, message = "Åtkomst nekad" });

            var regionId = _calendar.RegionIdForClub(clubId);
            var region = _calendar.Region(regionId);
            var list = SafeList(() => _apps.ForClub(clubId));
            var holders = regionId > 0 ? _uppdrag.Holders(regionId, BoardRoleDefinitions.RoleTavlingsansvarig) : new();
            var year = DateTime.Today.Year;
            var linksThisYear = list.Count(a => !string.IsNullOrEmpty(a.LinkSentTo) && a.CreatedAt.Year == year);

            return Json(new
            {
                success = true,
                region = region == null ? null : new { id = region.Id, name = region.Name, url = region.Url },
                kretsReceivesLoggedIn = holders.Count > 0,
                linksThisYear,
                deadlines = regionId > 0 ? SafeList(() => _apps.Deadlines(regionId))
                    .Where(d => d.Year >= year).Select(d => new { d.Year, d.Level, lastDate = d.LastDate.ToString("yyyy-MM-dd") }) : null,
                levels = CompetitionApplicationRules.ApplicableLevels.Select(l => new { value = l, label = CompetitionLevel.Find(l)?.Label ?? l }),
                disciplines = HpskSite.Models.CompetitionTypes.All.Select(t => new { value = t.Id, label = t.Name }),
                applications = list.Select(a => Dto(a, forClub: true))
            });
        }

