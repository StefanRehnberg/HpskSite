        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> SaveApplication([FromBody] SaveApplicationRequest req)
        {
            if (req == null) return Json(new { success = false, message = "Tom begäran." });
            var me = await CurrentMemberAsync();
            if (me == null) return Json(new { success = false, message = "Logga in först." });

            // Kretsen härleds ur klubben, aldrig ur klienten.
            int regionId = req.ClubId > 0 ? _calendar.RegionIdForClub(req.ClubId) : req.RegionId;
            if (regionId <= 0) return Json(new { success = false, message = "Klubbens krets hittades inte." });
            if (!await CanClubAsync(req.ClubId, regionId)) return Json(new { success = false, message = "Åtkomst nekad" });

            var draft = new CompetitionApplication
            {
                RegionId = regionId,
                ClubId = Math.Max(0, req.ClubId),
                Level = (req.Level ?? "").Trim(),
                Discipline = (req.Discipline ?? "").Trim(),
                Name = (req.Name ?? "").Trim(),
                CompetitionDate = ParseDate(req.CompetitionDate) ?? default,
                EndDate = ParseDate(req.EndDate),
                ReserveDate = ParseDate(req.ReserveDate),
                RangeId = req.RangeId is > 0 ? req.RangeId : null,
                Place = Clip(req.Place, 200),
                ContactMemberId = me.Id,
                ContactName = Clip(req.ContactName, 200) ?? DisplayName(me),
                ContactEmail = Clip(req.ContactEmail, 200) ?? me.Email,
                ContactPhone = Clip(req.ContactPhone, 50),
                Classes = Clip(req.Classes, 400),
                Note = Clip(req.Note, 4000)
            };

            CompetitionApplication? saved;
            string? err;
            bool justSubmitted;
            if (req.Id > 0)
            {
                var existing = _apps.Get(req.Id);
                if (existing == null || existing.ClubId != draft.ClubId || existing.RegionId != regionId)
                    return Json(new { success = false, message = "Ansökan hittades inte." });
                (saved, err) = _apps.UpdateContent(req.Id, draft, me.Id, DisplayName(me));
                justSubmitted = false;
                if (saved != null && req.Submit == "1" && saved.Status == CompetitionApplicationStatus.Utkast)
                {
                    (saved, err) = _apps.Submit(saved.Id, me.Id, DisplayName(me));
                    justSubmitted = saved != null;
                }
            }
            else
            {
                (saved, err) = _apps.Create(draft, req.Submit == "1", me.Id, DisplayName(me));
                justSubmitted = saved?.Status == CompetitionApplicationStatus.Inskickad;
            }
            if (saved == null) return Json(new { success = false, message = err });

            var notified = 0;
            var lateNote = LateNote(saved);
            if (justSubmitted || (req.Id > 0 && saved.Status == CompetitionApplicationStatus.Inskickad))
                notified = await NotifyKretsAsync(saved, me, justSubmitted ? "Ny ansökan" : "Ändrad ansökan");

            _calendar.Invalidate();
            return Json(new
            {
                success = true,
                application = Dto(saved, forClub: true),
                notified,
                caseLinks = await CaseLinksForSupportAsync(),
                message = saved.Status == CompetitionApplicationStatus.Utkast
                    ? "Ansökan sparad som utkast. Den skickas till kretsen när du trycker Skicka in."
                    : (notified > 0
                        ? $"Ansökan är skickad till kretsen ({notified} {(notified == 1 ? "mottagare" : "mottagare")})."
                        : "Ansökan är sparad hos kretsen, men inget mejl kunde skickas. Kretsen ser den när någon där loggar in.")
                    + (lateNote != null ? " " + lateNote : "")
            });
        }

        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> SubmitApplication(int id)
        {
            var (a, me, deny) = await ClubActionAsync(id);
            if (deny != null) return deny;
            var (saved, err) = _apps.Submit(id, me!.Id, DisplayName(me));
            if (saved == null) return Json(new { success = false, message = err });
            var n = await NotifyKretsAsync(saved, me, "Ny ansökan");
            _calendar.Invalidate();
            return Json(new { success = true, notified = n, caseLinks = await CaseLinksForSupportAsync(), message = n > 0 ? "Ansökan är skickad till kretsen." : "Ansökan är inskickad, men inget mejl kunde skickas." });
        }

